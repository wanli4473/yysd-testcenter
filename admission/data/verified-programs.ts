export type VerifiedProgram = SchoolSeed & {
  /** ISO date the row was last checked against the official URL */
  verifiedDate: string;
};

function v(
  partial: Omit<VerifiedProgram, "slug" | "verifiedDate"> & { verifiedDate?: string }
): VerifiedProgram {
  return {
    ...partial,
    slug: slugify([partial.name, partial.program, partial.degree, partial.country]),
    verifiedDate: partial.verifiedDate || "2026-07-29",
  };
}

