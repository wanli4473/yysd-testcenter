function phraseZh(en) {
  var s = String(en || "").trim();
  if (EXACT[s]) return EXACT[s];
  var low = s.toLowerCase();
  for (var i = 0; i < PHRASE.length; i++) {
    if (low.indexOf(PHRASE[i][0]) >= 0) return PHRASE[i][1];
  }
  var words = low.replace(/[^a-z0-9\s-]/g, " ").split(/\s+/).filter(Boolean);
  var zh = [];
  var hit = 0;
  words.forEach(function (w) {
    if (WORD[w]) { zh.push(WORD[w]); hit += 1; }
  });
  if (hit >= Math.min(2, words.length) && zh.length) return zh.join("");
  return s;
}

function titleZh(en) {
  if (EXACT[en]) return EXACT[en];
  var key = String(en || "");
  var hit = Object.keys(EXACT).filter(function (k) { return k.toLowerCase() === key.toLowerCase(); })[0];
  return hit ? EXACT[hit] : phraseZh(en);
}

