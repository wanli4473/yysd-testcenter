#!/usr/bin/env node
var fs = require("fs");
var path = require("path");
var root = path.join(__dirname, "..", "library", "mock", "cambridge-reading");
function read(n) { return fs.readFileSync(path.join(root, n), "utf8"); }
function must(cond, msg) { if (!cond) throw new Error(msg); }
function parseTest(html) {
  var i = html.indexOf("const TEST");
  var j = html.indexOf("const BAND_TABLE");
  must(i >= 0 && j > i, "TEST block");
  return new Function(html.slice(i, j) + "; return TEST;")();
}

var t1 = read("cambridge-18-test-1-reading.html");
must(t1.indexOf("2,000 refrigerated kilometres") >= 0, "T1 Hardy 2000 km quote");
must(t1.indexOf("underground carparks") >= 0, "T1 last paras mushrooms/carparks");
must(t1.indexOf("wheat, rice or potatoes") < 0, "T1 no invented wheat/rice para");
must(parseTest(t1).passages.reduce(function (n, p) { return n + p.groups.reduce(function (m, g) { return m + g.questions.length; }, 0); }, 0) === 40, "T1 40 qs");

var t2 = read("cambridge-18-test-2-reading.html");
must(t2.indexOf("theories about the transportation of the bluestones") >= 0, "T2 Q3-5 theories");
must(t2.indexOf("archaeological:") >= 0 && t2.indexOf("geological:") >= 0, "T2 nested headings");
must(t2.indexOf("they were brought from Wales by") >= 0, "T2 Q5 geological");
must(t2.indexOf("a geological theory says") < 0, "T2 no flattened Q5");

var t3 = read("cambridge-18-test-3-reading.html");
must(t3.indexOf("Using wood, however, has its challenges") >= 0, "T3 Q5-8 full summary");
must(t3.indexOf("how much noise is generated by the process") >= 0, "T3 Q8 noise");
must(t3.indexOf("The Model E was road-tested in 1924") >= 0, "T3 Q24-26 full");
must(t3.indexOf("Melbourne Education Research Institute") >= 0, "T3 Q31-35 full");
must(t3.indexOf("A further issue is that teachers tend to have") >= 0, "T3 Q35 further issue");

var t4 = read("cambridge-18-test-4-reading.html");
must(t4.indexOf("lessening the likelihood that floods will occur") >= 0, "T4 Q6-9 full summary");
must(t4.indexOf("Benefits include reducing spending on") < 0, "T4 no truncated Q6-9");
must(t4.indexOf("where the notion of innate intelligence first began") >= 0, "T4 Q14 full");
must(t4.indexOf("The methodology behind the growth mindset studies") >= 0, "T4 Q17 full");
must(t4.indexOf("hazardous exploration") >= 0, "T4 Q35 option H");
must(t4.indexOf("One of the remarkable things about Wegener") >= 0, "T4 Q31-36 full");
must(t4.indexOf("He was not a particularly ambitious person") >= 0, "T4 Q38 full");

var c19 = read("cambridge-19-test-2-reading.html");
must(c19.indexOf("{h:`Communications`}") >= 0, "C19 T2 Communications heading");
must(c19.indexOf("Cooke and Wheatstone patented the first telegraphy system") >= 0, "C19 T2 telegraphy");
must(c19.indexOf("movement of the <Q n=\"1\">") >= 0, "C19 T2 Q1 piston stem");

console.log("check_c18_reading: ok");
