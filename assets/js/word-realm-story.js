  chapterOfRegion: function (region) {
    var list = this.chapters || [];
    for (var i = 0; i < list.length; i++) {
      if (list[i].region === region) return list[i];
    }
    return list[0] || null;
  },

  bossOf: function (shrineId) {
    return (this.bosses && this.bosses[shrineId]) || null;
  },

  isBossShrine: function (shrineId) {
    return !!this.bossOf(shrineId);
  },

  dreamAt: function (clearedCount) {
    var list = this.dreams || [];
    for (var i = 0; i < list.length; i++) {
      if (list[i].afterShrine === clearedCount) return list[i];
    }
    return null;
  },

